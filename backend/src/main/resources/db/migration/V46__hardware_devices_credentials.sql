-- Devices authenticate with an API key (stored as SHA-256 hash) so hardware
-- can post scans without a staff user session.
ALTER TABLE access_devices ADD COLUMN api_key_hash VARCHAR(64);
ALTER TABLE access_devices ADD COLUMN created_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE access_devices ADD COLUMN last_seen_at TIMESTAMP WITH TIME ZONE;

CREATE UNIQUE INDEX uq_access_devices_api_key ON access_devices (api_key_hash);

-- Maps hardware identifiers (card UID, fingerprint template id, QR payload)
-- to gym members, so raw scans resolve to real users automatically.
CREATE TABLE member_credentials (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gym_id           BIGINT                   NOT NULL REFERENCES gyms (id),
    user_id          BIGINT                   NOT NULL REFERENCES users (id),
    type             VARCHAR(20)              NOT NULL,
    credential_value VARCHAR(150)             NOT NULL,
    label            VARCHAR(100),
    active           BOOLEAN                  NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at       TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_member_credentials_lookup ON member_credentials (gym_id, credential_value);
CREATE INDEX idx_member_credentials_member ON member_credentials (gym_id, user_id, active);

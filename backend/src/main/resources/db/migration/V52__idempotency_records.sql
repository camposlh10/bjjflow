-- Generic idempotency for writes sent with an Idempotency-Key header. The app
-- queues changes while offline and replays them later; if a replay repeats a
-- request that already went through (its response was lost), the stored
-- response is returned instead of applying the change twice.
CREATE TABLE idempotency_records (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT                   NOT NULL,
    idem_key      VARCHAR(100)             NOT NULL,
    method        VARCHAR(10)              NOT NULL,
    path          VARCHAR(500)             NOT NULL,
    -- IN_PROGRESS while the first request runs, DONE once its response is stored.
    state         VARCHAR(12)              NOT NULL,
    status        INT,
    content_type  VARCHAR(100),
    response_body TEXT,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_idempotency_user_key UNIQUE (user_id, idem_key)
);
CREATE INDEX idx_idempotency_created ON idempotency_records (created_at);

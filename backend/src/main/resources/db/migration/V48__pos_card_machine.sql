-- POS / card machine integration.

-- Reference the attendant ties to the card-machine sale so the webhook can
-- match the transaction back to the invoice.
ALTER TABLE invoices ADD COLUMN payment_reference VARCHAR(40);
UPDATE invoices SET payment_reference = 'INV-' || id WHERE payment_reference IS NULL;
CREATE UNIQUE INDEX uq_invoices_payment_reference ON invoices (payment_reference);

-- Full card data on transactions (nullable: manual payments don't have them).
ALTER TABLE payment_transactions ADD COLUMN payment_method VARCHAR(20);
ALTER TABLE payment_transactions ADD COLUMN card_brand VARCHAR(30);
ALTER TABLE payment_transactions ADD COLUMN installments INT;
ALTER TABLE payment_transactions ADD COLUMN status VARCHAR(20) DEFAULT 'CONFIRMED' NOT NULL;
ALTER TABLE payment_transactions ADD COLUMN authorization_code VARCHAR(60);
ALTER TABLE payment_transactions ADD COLUMN provider_name VARCHAR(60);

-- One row per registered card machine / gateway account. Authenticates
-- webhooks with a hashed API key, like access_devices does for turnstiles.
CREATE TABLE pos_integrations (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gym_id       BIGINT                   NOT NULL REFERENCES gyms (id),
    name         VARCHAR(100)             NOT NULL,
    provider_name VARCHAR(60)             NOT NULL,
    api_key_hash VARCHAR(64),
    active       BOOLEAN                  NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    last_seen_at TIMESTAMP WITH TIME ZONE
);

CREATE UNIQUE INDEX uq_pos_integrations_api_key ON pos_integrations (api_key_hash);
CREATE INDEX idx_pos_integrations_gym ON pos_integrations (gym_id, active);

-- Raw webhook audit trail: every provider callback is stored before being
-- processed, so nothing is lost and ambiguous payments can be reviewed.
CREATE TABLE pos_webhook_events (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gym_id                  BIGINT                   NOT NULL REFERENCES gyms (id),
    integration_id          BIGINT                   NOT NULL REFERENCES pos_integrations (id),
    external_transaction_id VARCHAR(150)             NOT NULL,
    payment_reference       VARCHAR(40),
    invoice_id              BIGINT                   REFERENCES invoices (id),
    amount                  NUMERIC(12, 2)           NOT NULL,
    payment_method          VARCHAR(20),
    card_brand              VARCHAR(30),
    installments            INT,
    authorization_code      VARCHAR(60),
    paid_at                 TIMESTAMP WITH TIME ZONE NOT NULL,
    status                  VARCHAR(30)              NOT NULL,
    notes                   VARCHAR(500),
    processed_at            TIMESTAMP WITH TIME ZONE,
    created_at              TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_pos_webhook_tx UNIQUE (gym_id, external_transaction_id)
);

CREATE INDEX idx_pos_webhook_gym_status ON pos_webhook_events (gym_id, status, created_at);

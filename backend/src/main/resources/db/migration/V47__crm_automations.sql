-- Automation engine log. The unique (type, ref_key) pair makes every automation
-- idempotent: a job re-run can never send the same notification twice.
CREATE TABLE automation_events (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gym_id     BIGINT                   NOT NULL REFERENCES gyms (id),
    type       VARCHAR(40)              NOT NULL,
    ref_key    VARCHAR(150)             NOT NULL,
    user_id    BIGINT,
    title      VARCHAR(150)             NOT NULL,
    body       VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_automation_event UNIQUE (type, ref_key)
);

CREATE INDEX idx_automation_events_gym ON automation_events (gym_id, created_at);


-- Background job queue (transactional outbox). A job row is written in the same
-- transaction as the change that caused it, so a rolled-back change never sends
-- a push or email, and a committed one is never lost if the server restarts.
CREATE TABLE jobs (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type         VARCHAR(60)              NOT NULL,
    -- JSON arguments; cleared once the job succeeds (it may hold an email body).
    payload      TEXT,
    -- PENDING -> RUNNING -> DONE, or back to PENDING for a retry, or FAILED.
    status       VARCHAR(12)              NOT NULL,
    attempts     INT                      NOT NULL DEFAULT 0,
    max_attempts INT                      NOT NULL,
    run_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    -- While RUNNING: when the claim expires (a crashed worker's job is picked up again).
    locked_until TIMESTAMP WITH TIME ZONE,
    last_error   VARCHAR(1000),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at  TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_jobs_due ON jobs (status, run_at);
CREATE INDEX idx_jobs_finished ON jobs (status, finished_at);

-- One row per scheduled task: whichever server instance moves locked_until
-- forward first runs the task, the others skip it.
CREATE TABLE scheduler_locks (
    name         VARCHAR(60) PRIMARY KEY,
    locked_until TIMESTAMP WITH TIME ZONE NOT NULL,
    locked_by    VARCHAR(100)
);

-- Automations run at the gym's local time instead of the server's.
ALTER TABLE gyms ADD COLUMN timezone VARCHAR(40) NOT NULL DEFAULT 'America/Sao_Paulo';

-- Idempotency: the app tags each check-in and message with its own id, so
-- retrying after a lost response (or flushing an offline queue) never duplicates it.
ALTER TABLE check_ins ADD COLUMN client_id VARCHAR(64);
CREATE UNIQUE INDEX uq_check_ins_client ON check_ins (user_id, client_id);
ALTER TABLE messages ADD COLUMN client_id VARCHAR(64);
CREATE UNIQUE INDEX uq_messages_client ON messages (sender_id, client_id);

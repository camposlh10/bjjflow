-- Server-side refresh tokens. Each login starts a "family"; every refresh rotates
-- the token within that family. Only a SHA-256 hash is stored, so a database leak
-- does not expose usable tokens. Revoking a family ends that device's session.
CREATE TABLE refresh_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT                   NOT NULL REFERENCES users (id),
    family_id  VARCHAR(36)              NOT NULL,
    token_hash VARCHAR(64)              NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    rotated_at TIMESTAMP WITH TIME ZONE,
    revoked_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_refresh_tokens_hash UNIQUE (token_hash)
);
CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_id);
CREATE INDEX idx_refresh_tokens_family ON refresh_tokens (family_id);
CREATE INDEX idx_refresh_tokens_expires ON refresh_tokens (expires_at);

-- Set whenever the password changes. Legacy stateless (JWT) refresh tokens issued
-- before this instant are refused, so a password change also ends old sessions.
ALTER TABLE users ADD COLUMN credentials_changed_at TIMESTAMP WITH TIME ZONE;

-- Caps guesses per emailed reset code (a 6-digit code is brute-forceable otherwise).
ALTER TABLE password_reset_tokens ADD COLUMN attempts INTEGER NOT NULL DEFAULT 0;

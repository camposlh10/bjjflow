-- Phase 4 of the turnstile / face-scanner integration: enrolling members on
-- devices from the CRM, through the gym's bridge.

-- Which bridge reaches the device, and its address on the gym's network.
ALTER TABLE access_devices ADD COLUMN bridge_id BIGINT REFERENCES access_bridges (id);
ALTER TABLE access_devices ADD COLUMN lan_host VARCHAR(100);

-- LGPD: a member's consent to have their face used for gym access. Staff
-- record it (e.g. from a signed form); revoking removes the face from devices.
-- The face itself is never stored here: the device captures and keeps it.
CREATE TABLE biometric_consents (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gym_id              BIGINT                   NOT NULL REFERENCES gyms (id),
    user_id             BIGINT                   NOT NULL REFERENCES users (id),
    terms_version       VARCHAR(20)              NOT NULL,
    granted_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    recorded_by_user_id BIGINT                   NOT NULL REFERENCES users (id),
    revoked_at          TIMESTAMP WITH TIME ZONE,
    revoked_by_user_id  BIGINT                   REFERENCES users (id)
);

CREATE INDEX idx_biometric_consents_member ON biometric_consents (gym_id, user_id);

-- A member registered (or being registered/removed) on one device.
CREATE TABLE device_enrollments (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gym_id             BIGINT                   NOT NULL REFERENCES gyms (id),
    user_id            BIGINT                   NOT NULL REFERENCES users (id),
    device_id          BIGINT                   NOT NULL REFERENCES access_devices (id),
    method             VARCHAR(10)              NOT NULL,
    card_value         VARCHAR(40),
    status             VARCHAR(20)              NOT NULL,
    command_id         BIGINT                   REFERENCES bridge_commands (id),
    last_error         VARCHAR(500),
    created_by_user_id BIGINT                   NOT NULL REFERENCES users (id),
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_device_enrollments_member ON device_enrollments (gym_id, user_id);
CREATE INDEX idx_device_enrollments_command ON device_enrollments (command_id);

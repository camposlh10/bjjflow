-- Phase 3 of the turnstile / face-scanner integration: the BJJ Flow Bridge,
-- a small app on the gym's front-desk PC. It relays device notifications to
-- the cloud (with an offline queue) and runs commands the cloud can't send
-- straight into the gym's network.

CREATE TABLE access_bridges (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gym_id       BIGINT                   NOT NULL REFERENCES gyms (id),
    name         VARCHAR(100)             NOT NULL,
    api_key_hash VARCHAR(64)              NOT NULL,
    active       BOOLEAN                  NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    last_seen_at TIMESTAMP WITH TIME ZONE,
    version      VARCHAR(40),
    queue_depth  INT
);

CREATE UNIQUE INDEX uq_access_bridges_api_key ON access_bridges (api_key_hash);
CREATE INDEX idx_access_bridges_gym ON access_bridges (gym_id, active);

-- Work for a bridge. PENDING -> SENT (handed out on a heartbeat) -> DONE or
-- FAILED. A SENT command with no result goes back to PENDING after a while,
-- up to a few attempts.
CREATE TABLE bridge_commands (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bridge_id    BIGINT                   NOT NULL REFERENCES access_bridges (id),
    type         VARCHAR(30)              NOT NULL,
    payload      TEXT,
    status       VARCHAR(20)              NOT NULL,
    attempts     INT                      NOT NULL DEFAULT 0,
    result       VARCHAR(4000),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    sent_at      TIMESTAMP WITH TIME ZONE,
    completed_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_bridge_commands_queue ON bridge_commands (bridge_id, status, id);

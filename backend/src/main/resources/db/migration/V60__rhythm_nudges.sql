-- Smart reminders: each member's training rhythm over the last 21 days, and
-- at most one push per day chosen from it.

ALTER TABLE users ADD COLUMN smart_reminders BOOLEAN DEFAULT TRUE NOT NULL;

-- The latest rhythm read for a member (rebuilt each morning they're planned).
CREATE TABLE user_rhythms (
    user_id        BIGINT PRIMARY KEY REFERENCES users (id),
    computed_on    DATE        NOT NULL, -- the member's local date
    state          VARCHAR(10) NOT NULL, -- LEARNING | ACTIVE | LAPSING | DORMANT
    training_days  INT         NOT NULL, -- distinct days trained in the 21-day window
    habit_mask     INT         NOT NULL, -- bit (ISO weekday - 1) set when trained that weekday in 2 of 3 weeks
    start_minutes  VARCHAR(60),          -- usual start per weekday, minutes after midnight, Mon..Sun, blank = unknown
    usual_start    INT,
    usual_log      INT,                  -- when they usually log a session (they're on the phone then)
    median_gap     INT,                  -- days between sessions
    long_gap       INT,                  -- their longer usual gaps (80th percentile); slipping starts 2 days past it
    last_training  DATE,
    zone           VARCHAR(40) NOT NULL
);

-- One row per member per local day: the push chosen for that day (PLANNED →
-- SENT or SKIPPED), or NONE when nothing was worth sending.
CREATE TABLE nudges (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT                   NOT NULL REFERENCES users (id),
    local_date  DATE                     NOT NULL,
    kind        VARCHAR(20)              NOT NULL,
    status      VARCHAR(10)              NOT NULL,
    send_at     TIMESTAMP WITH TIME ZONE,
    title       VARCHAR(120),
    body        VARCHAR(300),
    skip_reason VARCHAR(30),
    sent_at     TIMESTAMP WITH TIME ZONE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_nudge_day UNIQUE (user_id, local_date)
);

CREATE INDEX idx_nudges_due ON nudges (status, send_at);
CREATE INDEX idx_nudges_user_sent ON nudges (user_id, sent_at);

CREATE TABLE access_devices (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gym_id   BIGINT       NOT NULL REFERENCES gyms (id),
    name     VARCHAR(100) NOT NULL,
    type     VARCHAR(40)  NOT NULL,
    provider VARCHAR(100),
    location VARCHAR(150),
    active   BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE INDEX idx_access_devices_gym ON access_devices (gym_id, active);

CREATE TABLE raw_access_events (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gym_id             BIGINT                   NOT NULL REFERENCES gyms (id),
    device_id          BIGINT                   NOT NULL REFERENCES access_devices (id),
    student_user_id    BIGINT,
    external_member_id VARCHAR(100),
    event_time         TIMESTAMP WITH TIME ZONE NOT NULL,
    source             VARCHAR(30)              NOT NULL,
    status             VARCHAR(40)              NOT NULL,
    processed          BOOLEAN                  NOT NULL DEFAULT FALSE,
    processed_at       TIMESTAMP WITH TIME ZONE,
    matched_class_id   BIGINT                   REFERENCES gym_classes (id),
    notes              VARCHAR(1000)
);

CREATE INDEX idx_raw_access_gym_time ON raw_access_events (gym_id, event_time);
CREATE INDEX idx_raw_access_device_time ON raw_access_events (device_id, event_time);
CREATE INDEX idx_raw_access_member_time ON raw_access_events (student_user_id, event_time);

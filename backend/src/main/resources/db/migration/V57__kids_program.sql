-- Kids program, phase 1: children, their guardians, who may collect them,
-- health info and the gym's enrolment documents. The gym owner configures the
-- program in the CRM; staff keep each child's record.

-- A birth date keeps the age right over time (the age column goes stale).
ALTER TABLE users ADD COLUMN birth_date DATE;

-- A managed profile is a child the gym registered: it has no login, so no
-- email or password. Guardians see it through their own accounts.
ALTER TABLE users ADD COLUMN managed BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE users ALTER COLUMN email DROP NOT NULL;
ALTER TABLE users ALTER COLUMN password_hash DROP NOT NULL;

-- The owner's rules for the kids program. No row means not set up yet.
CREATE TABLE gym_kids_settings (
    gym_id                   BIGINT PRIMARY KEY REFERENCES gyms (id),
    checkout_required        BOOLEAN                  NOT NULL,
    pickup_list_only         BOOLEAN                  NOT NULL,
    late_pickup_minutes      INT                      NOT NULL,
    missing_documents_policy VARCHAR(10)              NOT NULL, -- WARN | BLOCK
    adult_age                INT                      NOT NULL, -- students this age or older leave the program
    updated_by_user_id       BIGINT                   REFERENCES users (id),
    updated_at               TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE kids_age_groups (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gym_id   BIGINT      NOT NULL REFERENCES gyms (id),
    name     VARCHAR(60) NOT NULL,
    min_age  INT         NOT NULL,
    max_age  INT         NOT NULL,
    position INT         NOT NULL
);

CREATE INDEX idx_kids_age_groups_gym ON kids_age_groups (gym_id);

-- Documents the gym collects (waiver, medical form, image consent...).
CREATE TABLE gym_document_types (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gym_id         BIGINT                   NOT NULL REFERENCES gyms (id),
    name           VARCHAR(80)              NOT NULL,
    kind           VARCHAR(20)              NOT NULL, -- WAIVER | MEDICAL | IMAGE_CONSENT | OTHER
    required       BOOLEAN                  NOT NULL,
    renewal_months INT,                                -- null: never expires
    active         BOOLEAN                  NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_gym_document_types_gym ON gym_document_types (gym_id);

-- A document a child's guardian signed. The latest one per type counts.
CREATE TABLE student_documents (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gym_id              BIGINT                   NOT NULL REFERENCES gyms (id),
    student_user_id     BIGINT                   NOT NULL REFERENCES users (id),
    document_type_id    BIGINT                   NOT NULL REFERENCES gym_document_types (id),
    signed_by_name      VARCHAR(120)             NOT NULL,
    signed_on           DATE                     NOT NULL,
    expires_on          DATE,
    recorded_by_user_id BIGINT                   NOT NULL REFERENCES users (id),
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_student_documents_student ON student_documents (gym_id, student_user_id);

-- A child's guardian. The gym creates it with the contact details; the guardian
-- links their own account by entering the invite code in the app. Guardians
-- may always collect the child.
CREATE TABLE guardianships (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gym_id                BIGINT                   NOT NULL REFERENCES gyms (id),
    student_user_id       BIGINT                   NOT NULL REFERENCES users (id),
    guardian_user_id      BIGINT                   REFERENCES users (id),
    name                  VARCHAR(120)             NOT NULL,
    relationship          VARCHAR(20)              NOT NULL, -- MOTHER | FATHER | GRANDPARENT | OTHER
    phone                 VARCHAR(30),
    email                 VARCHAR(255),
    primary_contact       BOOLEAN                  NOT NULL,
    financial_responsible BOOLEAN                  NOT NULL,
    status                VARCHAR(20)              NOT NULL, -- PENDING | ACTIVE | REVOKED
    invite_code           VARCHAR(12) UNIQUE,
    invite_expires_at     TIMESTAMP WITH TIME ZONE,
    linked_at             TIMESTAMP WITH TIME ZONE,
    created_by_user_id    BIGINT                   NOT NULL REFERENCES users (id),
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at            TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_guardianships_student ON guardianships (gym_id, student_user_id);
CREATE INDEX idx_guardianships_guardian ON guardianships (guardian_user_id);

-- Other people who may collect a child, or (blocked) who must not.
CREATE TABLE authorized_pickups (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gym_id             BIGINT                   NOT NULL REFERENCES gyms (id),
    student_user_id    BIGINT                   NOT NULL REFERENCES users (id),
    name               VARCHAR(120)             NOT NULL,
    relationship       VARCHAR(60),
    phone              VARCHAR(30),
    notes              VARCHAR(300),
    blocked            BOOLEAN                  NOT NULL,
    created_by_user_id BIGINT                   NOT NULL REFERENCES users (id),
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_authorized_pickups_student ON authorized_pickups (gym_id, student_user_id);

-- Emergency card: what a coach needs if something happens on the mat.
CREATE TABLE student_health_info (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gym_id             BIGINT                   NOT NULL REFERENCES gyms (id),
    student_user_id    BIGINT                   NOT NULL REFERENCES users (id),
    blood_type         VARCHAR(5),
    allergies          VARCHAR(500),
    conditions         VARCHAR(500),
    medications        VARCHAR(500),
    health_plan        VARCHAR(120),
    emergency_notes    VARCHAR(500),
    updated_by_user_id BIGINT                   NOT NULL REFERENCES users (id),
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_student_health_info UNIQUE (gym_id, student_user_id)
);

CREATE TABLE payment_plans (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gym_id         BIGINT                   NOT NULL REFERENCES gyms (id),
    member_user_id BIGINT                   NOT NULL REFERENCES users (id),
    name           VARCHAR(120)             NOT NULL,
    amount         NUMERIC(12, 2)           NOT NULL,
    billing_cycle  VARCHAR(20)              NOT NULL,
    start_date     DATE                     NOT NULL,
    next_due_date  DATE                     NOT NULL,
    active         BOOLEAN                  NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_payment_plans_gym_member ON payment_plans (gym_id, member_user_id, active);

CREATE TABLE invoices (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gym_id          BIGINT                   NOT NULL REFERENCES gyms (id),
    member_user_id  BIGINT                   NOT NULL REFERENCES users (id),
    payment_plan_id BIGINT                   REFERENCES payment_plans (id),
    description     VARCHAR(255)             NOT NULL,
    amount          NUMERIC(12, 2)           NOT NULL,
    due_date        DATE                     NOT NULL,
    status          VARCHAR(20)              NOT NULL,
    provider        VARCHAR(20)              NOT NULL,
    paid_at         TIMESTAMP WITH TIME ZONE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_invoices_gym_status_due ON invoices (gym_id, status, due_date);
CREATE INDEX idx_invoices_gym_member ON invoices (gym_id, member_user_id);

CREATE TABLE payment_transactions (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gym_id                  BIGINT                   NOT NULL REFERENCES gyms (id),
    invoice_id              BIGINT                   NOT NULL UNIQUE REFERENCES invoices (id),
    amount                  NUMERIC(12, 2)           NOT NULL,
    provider                VARCHAR(20)              NOT NULL,
    external_transaction_id VARCHAR(150),
    paid_at                 TIMESTAMP WITH TIME ZONE NOT NULL,
    notes                   VARCHAR(500),
    created_at              TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_payment_transactions_gym_paid ON payment_transactions (gym_id, paid_at);

-- Rating (chess-style, never resets) and matches between two members:
-- first to 3 weekly rounds, where a round goes to whoever trained on more days.

-- One row per member who has earned or lost rating; no row means 1000.
-- Kept apart from users so profile saves never overwrite a rating change.
CREATE TABLE player_ratings (
    user_id            BIGINT PRIMARY KEY REFERENCES users (id),
    rating             INT                      NOT NULL DEFAULT 1000,
    accepts_challenges BOOLEAN                  NOT NULL DEFAULT TRUE,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE INDEX idx_player_ratings_rating ON player_ratings (rating DESC);

-- Every rating change. ref_key makes each award happen once
-- (a training day, a week's goal, a match).
CREATE TABLE rating_events (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT                   NOT NULL REFERENCES users (id),
    delta      INT                      NOT NULL,
    reason     VARCHAR(20)              NOT NULL, -- TRAINING | WEEKLY_GOAL | MATCH
    ref_key    VARCHAR(40)              NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_rating_event UNIQUE (user_id, reason, ref_key)
);

CREATE INDEX idx_rating_events_user_time ON rating_events (user_id, created_at);

CREATE TABLE matches (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    challenger_id     BIGINT                   NOT NULL REFERENCES users (id),
    opponent_id       BIGINT                   NOT NULL REFERENCES users (id),
    -- PENDING | ACTIVE | FINISHED | DECLINED | CANCELLED | EXPIRED
    status            VARCHAR(10)              NOT NULL,
    starts_on         DATE,
    challenger_rounds INT                      NOT NULL DEFAULT 0,
    opponent_rounds   INT                      NOT NULL DEFAULT 0,
    rounds_played     INT                      NOT NULL DEFAULT 0,
    winner_id         BIGINT                   REFERENCES users (id),
    end_reason        VARCHAR(10), -- FIRST_TO_3 | ROUND_CAP | FORFEIT
    challenger_delta  INT,
    opponent_delta    INT,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    responded_at      TIMESTAMP WITH TIME ZONE,
    finished_at       TIMESTAMP WITH TIME ZONE,
    version           BIGINT                   NOT NULL DEFAULT 0
);

CREATE INDEX idx_matches_challenger ON matches (challenger_id, status);
CREATE INDEX idx_matches_opponent ON matches (opponent_id, status);
CREATE INDEX idx_matches_status ON matches (status);

CREATE TABLE match_rounds (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id        BIGINT NOT NULL REFERENCES matches (id),
    round_no        INT    NOT NULL,
    starts_on       DATE   NOT NULL,
    ends_on         DATE   NOT NULL,
    challenger_days INT    NOT NULL,
    opponent_days   INT    NOT NULL,
    winner_id       BIGINT REFERENCES users (id), -- null: a tied week
    CONSTRAINT uq_match_round UNIQUE (match_id, round_no)
);

-- A finished match posted to Comunidade, or a repost of one.
CREATE TABLE match_posts (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id      BIGINT                   NOT NULL REFERENCES matches (id),
    user_id       BIGINT                   NOT NULL REFERENCES users (id),
    repost_of_id  BIGINT                   REFERENCES match_posts (id),
    caption       VARCHAR(280),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_match_post UNIQUE (match_id, user_id)
);

CREATE INDEX idx_match_posts_user_time ON match_posts (user_id, created_at DESC);
CREATE INDEX idx_match_posts_time ON match_posts (created_at DESC);
